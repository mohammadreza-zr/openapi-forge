const isObject = (value: unknown): value is Record<string, unknown> =>
  value !== null && typeof value === "object" && !Array.isArray(value);

/** Deep merge for plain objects; arrays and everything else are replaced. */
export function merge<T>(base: T, patch: unknown): T {
  if (patch === undefined) return base;
  if (!isObject(base) || !isObject(patch)) return patch as T;
  const out: Record<string, unknown> = { ...base };
  for (const [key, value] of Object.entries(patch)) {
    out[key] = key in base ? merge(base[key], value) : value;
  }
  return out as T;
}

export function defineConfig(config: ForgeConfig): ForgeConfig {
  return config;
}

async function exists(file: string): Promise<boolean> {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

/** The config file of `cwd` — the one named, or the first default found. */
export async function loadConfigFile(
  cwd: string,
  explicit?: string,
): Promise<{ file: string | null; config: ForgeConfig }> {
  const candidates = explicit ? [explicit] : CONFIG_FILES;
  for (const name of candidates) {
    const file = isAbsolute(name) ? name : resolve(cwd, name);
    if (!(await exists(file))) {
      if (explicit)
        throw new Error(`openapi-forge: config file not found — ${file}`);
      continue;
    }
    if (file.endsWith(".json")) {
      const { readFile } = await import("node:fs/promises");
      return { file, config: JSON.parse(await readFile(file, "utf8")) };
    }
    const mod = await import(pathToFileURL(file).href);
    const config = mod.default ?? mod.config ?? {};
    return {
      file,
      config: typeof config === "function" ? await config() : config,
    };
  }
  return { file: null, config: {} };
}

/**
 * The options of a run: defaults, then the config file, then the command
 * line. A custom client starts from no runtime of its own — the project says
 * where its transport lives — while the built-in one has it all.
 */
export function resolveOptions(
  fileConfig: ForgeConfig = {},
  cliOptions: ForgeConfig = {},
): ForgeOptions {
  const library = cliOptions.library ?? fileConfig.library ?? DEFAULTS.library;
  if (!LIBRARY_NAMES.includes(library)) {
    throw new Error(
      `openapi-forge: library must be one of ${LIBRARY_NAMES.join(", ")}, not ${JSON.stringify(library)}.`,
    );
  }
  const base = { ...DEFAULTS, runtime: builtinRuntime(library) };
  const merged = merge(merge(base, fileConfig), cliOptions);
  const named = (key: "headers" | "envelope" | "body" | "responseType") =>
    cliOptions.runtime?.requestKeys?.[key] ??
    fileConfig.runtime?.requestKeys?.[key];
  // A custom transport knows nothing of the keys the built-in one reads, so
  // they are only written for it when the project names them.
  if (merged.client === "custom") {
    for (const key of ["headers", "envelope", "body", "responseType"] as const) {
      if (named(key) === undefined) merged.runtime.requestKeys[key] = false;
    }
  }
  // The built-in clients hand the answer over as the client gives it: nothing
  // unwraps an envelope at run time. `@mrzr/api-client` itself takes the `data`
  // of a `{ data }` answer, so the types speak of `data` there; with any other
  // client the type is the whole answer.
  if (merged.client === "builtin") {
    if (named("envelope") === undefined) merged.runtime.requestKeys.envelope = false;
    const own = cliOptions.runtime?.envelope ?? fileConfig.runtime?.envelope;
    if (merged.http !== "api-client" && own === undefined) merged.runtime.envelope = false;
  }
  // `@mrzr/api-client`'s `delete` takes no body, so a DELETE with one is left out.
  if (merged.client === "builtin" && merged.http === "api-client") {
    if (named("body")) {
      throw new Error(
        'openapi-forge: runtime.requestKeys.body cannot be set with http: "api-client" — its delete takes no body. Use http: "fetch", "axios" or "angular".',
      );
    }
    merged.runtime.requestKeys.body = false;
  }
  if (!["builtin", "custom"].includes(merged.client)) {
    throw new Error(
      `openapi-forge: client must be "builtin" or "custom", not ${JSON.stringify(merged.client)}.`,
    );
  }
  if (!["hooks", "requests"].includes(merged.target)) {
    throw new Error(
      `openapi-forge: target must be "hooks" or "requests", not ${JSON.stringify(merged.target)}.`,
    );
  }
  if (!HTTP_CLIENTS.includes(merged.http)) {
    throw new Error(
      `openapi-forge: http must be one of ${HTTP_CLIENTS.join(", ")}, not ${JSON.stringify(merged.http)}.`,
    );
  }
  const infinite: unknown = merged.infinite;
  if (infinite) {
    merged.infinite = {
      start: "start",
      size: "offset",
      ...(infinite === true ? {} : (infinite as object)),
    };
  }
  for (const key of ["include", "exclude"] as const) {
    merged.tags[key] = [merged.tags[key] ?? []].flat();
  }
  return merged;
}
